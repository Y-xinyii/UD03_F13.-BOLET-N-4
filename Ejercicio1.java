public class Ejercicio1 {
    public static void main(String[] args){

        System.out.println("Mestra en una sola línea los múltiplos de 5 de 0 a 100, separados por un espacio, con for.");
        
        for(int i = 0; i <= 100; i+= 5){  //Suma de 5 en 5
            System.out.println(i + "");

        }
        
    }
}